import express from 'express';
import jwt from 'jsonwebtoken';
import User from '../models/User.js';
import Patient from '../models/Patient.js';
import { protect } from '../middleware/auth.js';

const router = express.Router();
const sign = (u) =>
  jwt.sign({ id: u._id, role: u.role }, process.env.JWT_SECRET || 'devsecret', { expiresIn: '1d' });

router.get('/setup-status', async (_req, res, next) => {
  try {
    const adminCount = await User.countDocuments({ role: 'admin' });
    res.json({ needsSetup: adminCount === 0, adminExists: adminCount > 0 });
  } catch (err) { next(err); }
});

router.post('/register', async (req, res, next) => {
  try {
    const adminExists = await User.findOne({ role: 'admin' });
    if (adminExists) {
      return res.status(403).json({
        message: 'Registration is disabled. An administrator already exists. Contact your system administrator.'
      });
    }

    const { name, email, password } = req.body;
    if (!name || !email || !password)
      return res.status(400).json({ message: 'Name, email, and password are required' });
    if (password.length < 8)
      return res.status(400).json({ message: 'Password must be at least 8 characters' });
    if (await User.findOne({ email }))
      return res.status(409).json({ message: 'Email already registered' });

    const user = await User.create({ name, email, password, role: 'admin' });

    res.status(201).json({
      user: { id: user._id, name: user.name, email: user.email, role: user.role, patientProfile: user.patientProfile || null },
      token: sign(user)
    });
  } catch (err) { next(err); }
});

router.post('/login', async (req, res, next) => {
  try {
    const { email, password } = req.body;
    const user = await User.findOne({ email }).select('+password');
    if (!user || !user.isActive || !(await user.comparePassword(password)))
      return res.status(401).json({ message: 'Invalid credentials' });

    res.json({
      user: { id: user._id, name: user.name, email: user.email, role: user.role, patientProfile: user.patientProfile || null },
      token: sign(user)
    });
  } catch (err) { next(err); }
});

// ─────────────────────────────────────────────────────────────
// PATIENT PORTAL LOGIN (MR Number + Name)
// ─────────────────────────────────────────────────────────────
router.post('/patient-login', async (req, res, next) => {
  try {
    const { mrNumber, fullName } = req.body;
    if (!mrNumber || !fullName) {
      return res.status(400).json({ message: 'MR Number and Name are required' });
    }

    // Find the patient by MR Number and Name (case-insensitive)
    const patient = await Patient.findOne({
      mrNumber: mrNumber.trim(),
      fullName: { $regex: new RegExp(`^${fullName.trim()}$`, 'i') }
    });

    if (!patient) {
      return res.status(401).json({ message: 'Invalid MR Number or Name. Please check your lab receipt.' });
    }

    // Check if this patient already has a login account
    let user = await User.findOne({ patientProfile: patient._id });

    // If no account exists, create one automatically
    if (!user) {
      user = await User.create({
        name: patient.fullName,
        email: `${patient.mrNumber.toLowerCase()}@patient.mlmis.local`, // Auto-generated internal email
        password: 'AutoGenerated@123', // Will be hashed by the database
        role: 'patient',
        patientProfile: patient._id
      });
    }

    // Log them in
    res.json({
      user: { 
        id: user._id, 
        name: user.name, 
        email: user.email, 
        role: user.role, 
        patientProfile: user.patientProfile 
      },
      token: sign(user)
    });

  } catch (err) { next(err); }
});



router.get('/me', protect, (req, res) => {
  res.json({
    user: { id: req.user._id, name: req.user.name, email: req.user.email, role: req.user.role, patientProfile: req.user.patientProfile || null }
  });
});

router.post('/link-patient', protect, async (req, res, next) => {
  try {
    if (req.user.role !== 'patient')
      return res.status(400).json({ message: 'Only patient accounts can link' });
    const { mrNumber, contactNumber } = req.body;
    if (!mrNumber || !contactNumber)
      return res.status(400).json({ message: 'MR number and contact number required' });
    const patient = await Patient.findOne({ mrNumber, contactNumber });
    if (!patient) return res.status(404).json({ message: 'No patient record matches' });
    const alreadyLinked = await User.findOne({ patientProfile: patient._id, _id: { $ne: req.user._id } });
    if (alreadyLinked) return res.status(409).json({ message: 'Already linked' });
    req.user.patientProfile = patient._id;
    await req.user.save();
    res.json({ message: 'Linked', patient: { id: patient._id, mrNumber: patient.mrNumber, fullName: patient.fullName } });
  } catch (err) { next(err); }
});

export default router;